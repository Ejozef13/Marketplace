import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = spawnSync("npx", ["--yes", "supabase@3.0.0", "gen", "types", "typescript", "--local", "--schema", "public"],
  { cwd: root, encoding: "utf8" });
if (result.error) throw result.error;
if (result.status !== 0) {
  process.stderr.write(result.stderr ?? "Type generation failed.\n");
  process.exit(result.status ?? 1);
}
if (!result.stdout.includes("export type Database")) throw new Error("CLI did not return database types.");
// Never replace the committed file after a failed CLI invocation.
const source = ts.createSourceFile("database.types.ts", result.stdout, ts.ScriptTarget.Latest, true);
const formatted = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(source);
writeFileSync(new URL("../src/lib/supabase/database.types.ts", import.meta.url),
  "// Generated by npm run db:types from local Supabase. Do not edit manually.\n" + formatted);
console.log("Generated src/lib/supabase/database.types.ts from local migrations.");
